// Regenerates src/generated/{abis,deployments}.ts from the Foundry build and contracts/deployments/*.json.
// Run after `forge build` or a deployment: bun run sync
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../../..");
const out = join(import.meta.dir, "../src/generated");
mkdirSync(out, { recursive: true });

const contracts: [string, string][] = [
  ["SshAccount.sol", "SshAccount"],
  ["AccountFactory.sol", "AccountFactory"],
  ["KeyOracle.sol", "KeyOracle"],
  ["SshSigVerifier.sol", "SshSigVerifier"],
  ["OffchainResolver.sol", "OffchainResolver"],
  ["NameRegistrar.sol", "NameRegistrar"],
  ["BountyBoard.sol", "BountyBoard"],
  ["Escrow.sol", "Escrow"],
  ["ReportGate.sol", "ReportGate"],
];
const lowerFirst = (s: string) => s[0]!.toLowerCase() + s.slice(1);
let abis = "// Generated by packages/shared/scripts/sync.ts from contracts/out. Do not edit.\n";
for (const [file, name] of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "contracts/out", file, `${name}.json`), "utf8"));
  abis += `\nexport const ${lowerFirst(name)}Abi = ${JSON.stringify(artifact.abi)} as const;\n`;
}
writeFileSync(join(out, "abis.ts"), abis);

const read = (f: string) => {
  const p = join(root, "contracts/deployments", f);
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
};
const pick = (o: Record<string, unknown> | null, keys: string[]) => (o ? Object.fromEntries(keys.map((k) => [k, o[k]])) : null);
const core = pick(read("core.json"), ["Ed25519Verifier", "SshSigVerifier", "KeyOracle", "AccountFactory", "owner"]);
const extras = pick(read("extras.json"), ["BountyBoard", "Escrow"]);
const gate = pick(read("gate.json"), ["ReportGate"]);
const ens = pick(read("ens.json"), ["parentName", "resolver", "userRegistry", "nameRegistrar", "gatewaySigner"]);
writeFileSync(
  join(out, "deployments.ts"),
  "// Generated by packages/shared/scripts/sync.ts from contracts/deployments. Do not edit.\n" +
    "import type { Address } from \"viem\";\n\n" +
    "/// Same addresses on every chain (deterministic deployment). null until deployed.\n" +
    `export const CORE: { Ed25519Verifier: Address; SshSigVerifier: Address; KeyOracle: Address; AccountFactory: Address; owner: Address } | null = ${JSON.stringify(core, null, 2)};\n\n` +
    "/// BountyBoard and Escrow, same addresses on every chain they're deployed on. null until deployed.\n" +
    `export const EXTRAS: { BountyBoard: Address; Escrow: Address } | null = ${JSON.stringify(extras, null, 2)};\n\n` +
    "/// The CRE receiver in front of KeyOracle (and BountyBoard); same address on every chain. null until deployed.\n" +
    `export const GATE: { ReportGate: Address } | null = ${JSON.stringify(gate, null, 2)};\n\n` +
    "/// ENS on Sepolia. null until set up.\n" +
    `export const ENS_DEPLOYMENT: { parentName: string; resolver: Address; userRegistry: Address; nameRegistrar: Address; gatewaySigner: Address } | null = ${JSON.stringify(ens, null, 2)};\n`,
);
console.log(`wrote ${contracts.length} ABIs; core ${core ? "deployed" : "not deployed"}; extras ${extras ? "deployed" : "not deployed"}; gate ${gate ? "deployed" : "not deployed"}; ens ${ens ? "set up" : "not set up"}`);
